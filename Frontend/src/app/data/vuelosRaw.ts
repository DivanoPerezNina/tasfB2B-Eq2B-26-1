// Helper: IATA -> id
function id(iata: string): number {
  return aeropuertosBackend.find(a => a.iata === iata)?.id ?? 0;
}

// Helper: "HH:MM" -> minutos
function t(time: string): number {
  const [h, m] = time.split(':').map(Number);
  return h * 60 + m;
}

/**
 * Genera una ocupación mock realista (40-85% de capacidad)
 */
function mockOcupacion(cap: number): number {
  return Math.floor(cap * (0.4 + Math.random() * 0.45));
}

