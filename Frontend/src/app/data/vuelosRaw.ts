/**
 * Parsea las líneas raw y genera el array de Vuelo.
 * Se ejecuta una sola vez al importar el módulo.
 */
function parseAll(): Vuelo[] {
  return rawLines.split('\n').map(line => {
    const l = line.trim();
    if (!l) return null;
    const parts = l.split('-');
    if (parts.length < 5) return null;
    const origId = id(parts[0]);
    const destId = id(parts[1]);
    if (!origId || !destId) return null;
    return {
      idOrigen: origId,
      idDestino: destId,
      salidaUTC: t(parts[2]),
      llegadaUTC: t(parts[3]),
      capacidadMaxima: parseInt(parts[4], 10),
      ocupacionActual: mockOcupacion(parseInt(parts[4], 10)),
    } as Vuelo;
  }).filter(Boolean) as Vuelo[];
}

